#!/usr/bin/env python3
"""Схема данных модуля СИПРОДа: тематические секции и их назначение.

Раздел данных модуля СИПРОД состоит из разнородных элементов:
  * командные строки - образцы команд разбора (*0STA, *RG*RU);
  * имена модулей-генераторов режимов (NOTFOR, WRITEH, PAPAPR);
  * шаблоны формата - образцы строк, по которым разбираются команды;
  * маски признаков - наборы битов (LOG);
  * числовые константы - размеры, коды, номера (INT);
  * области переменных - свои ячейки модуля (BSS).

Каждая группа получает заголовок с её назначением (таблица SECTIONS
подготовлена по разбору кода модулей).
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

GEN = os.path.join(ROOT, "madlen-gen")

# род группы данных
KIND_CMD = "КОМАНДЫ"          # командные строки (*0STA, *RG*RU, ...)
KIND_MOD = "РЕЖИМЫ"           # имена модулей-генераторов (NOTFOR, WRITEH)
KIND_TPL = "ШАБЛОНЫ"          # образцы строк формата
KIND_MSK = "МАСКИ"            # маски признаков
KIND_NUM = "ЧИСЛА"            # числовые константы
KIND_VAR = "ПЕРЕМЕННЫЕ"       # области своих переменных

# назначение группы по умолчанию
DEFAULT_PURPOSE = {
    KIND_CMD: "КОМАНДНЫЕ СТРОКИ УПРАВЛЕНИЯ РАЗБОРОМ",
    KIND_MOD: "ИМЕНА МОДУЛЕЙ-ГЕНЕРАТОРОВ РЕЖИМОВ",
    KIND_TPL: "ОБРАЗЦЫ СТРОК ДЛЯ РАЗБОРА КОМАНД",
    KIND_MSK: "НАБОРЫ ПРИЗНАКОВ",
    KIND_NUM: "ЧИСЛОВЫЕ КОНСТАНТЫ: РАЗМЕРЫ, КОДЫ И НОМЕРА",
    KIND_VAR: "СВОИ ПЕРЕМЕННЫЕ МОДУЛЯ",
}

# разбор строки данных: (имя, тип, значение)
DATA_RE = re.compile(
    r"^\s*(?:([A-Za-zА-ЯЁ*][A-Za-zА-ЯЁ0-9_+*]*)?:)?,?"
    r"(BSS|ISO|INT|LOG|OCT|HEX|BIN)(?:,(.*))?$")


def group_of(name, kind, val):
    """Род группы данных по имени, типу и значению."""
    if kind == "BSS":
        return KIND_VAR
    if kind == "LOG":
        return KIND_MSK
    if kind == "INT":
        return KIND_NUM
    if kind == "ISO":
        text = (val or "").split(".")[0]
        m = re.search(r"\d+H(.*)$", text)
        body = (m.group(1) if m else text).strip().strip("'")
        if body.startswith("*"):
            return KIND_CMD
        if body and set(body) <= set(" .-I0123456789"):
            return KIND_TPL
        if body and body.replace(".", "").isalnum():
            return KIND_MOD
        return KIND_TPL
    return KIND_NUM


def section_text(module, kind):
    """Назначение группы для модуля (вручную или по умолчанию)."""
    return SECTIONS.get(module, {}).get(kind, DEFAULT_PURPOSE[kind])


def module_sections(module):
    """Секции данных модуля: [(вид, назначение, [(имя, тип, значение)])].

    Элементы одной группы собираются вместе, даже если в разделе данных
    они идут вперемежку.
    """
    path = os.path.join(GEN, module.replace("*", "#") + ".madlen")
    if not os.path.exists(path):
        return []
    order = []
    groups = {}
    for line in open(path, encoding="utf-8"):
        st = line.strip()
        if st.startswith(",DATA"):
            break
        m = DATA_RE.match(st)
        if not m:
            continue
        name, kind, val = m.group(1), m.group(2), (m.group(3) or "").strip()
        g = group_of(name, kind, val)
        if g not in groups:
            groups[g] = []
            order.append(g)
        groups[g].append((name, kind, val))
    return [(g, section_text(module, g), groups[g]) for g in order]


def main():
    lib = Library(IMAGE)
    for module in (sys.argv[1:] or sorted(lib.objects)):
        secs = module_sections(module)
        if not secs:
            continue
        print("=== %s" % module)
        for kind, purpose, items in secs:
            print("  -- %s: %s" % (kind, purpose))
            for name, kind2, val in items[:6]:
                print("       %-22s %-4s %s" % (name or "-", kind2, val[:28]))
            if len(items) > 6:
                print("       ... всего %d" % len(items))
        print()
    return 0


if __name__ == "__main__":
    from siprod_lib import Library                            # noqa: E402
    sys.exit(main())


