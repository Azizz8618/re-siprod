#!/bin/bash
# Сборка тестового задания тест-задание.b6: паспорт задания Диспака
# (шифр + том + ЕЕВ1А3), вызов редактора с тома 2348 (зона 2150(8)) и
# печать силуэт-схемы demo6-силуэт, диспетчерский конец ЕКОНЕЦ.
#
# Разметка схемы должна быть готова заранее (транслятор ДРАКОН):
#   ./прогнать-с-тома.sh drakon demo/demo6-силуэт.drakon > demo/demo6-разметка.txt
# Сборка колоды:
#   ./собрать-тест.sh
# Прогон:
#   DISPAK=путь/к/dispak BESM6_PATH="каталог/с/томом 2348:..." \
#       dispak тест-задание.b6
set -eu
HERE=$(cd "$(dirname "$0")" && pwd)
MRK="$HERE/../demo/demo6-разметка.txt"
[ -f "$MRK" ] || { echo "нет $MRK - сначала транслятор ДРАКОН (см. выше)" >&2; exit 1; }
{
    # --- паспорт задания ---
    echo "user 419999 зс5^"
    echo "лен 40(2348)^"
    echo "ЕЕВ1А3"
    # --- задача: редактор с тома, печать схемы ---
    echo "*name"
    echo "*call yesmemory"
    echo "*perso:402150"
    echo "*perso:402570,cont"
    echo "*call redakt"
    cat "$MRK"
    echo "*end file"
    echo '``````'
    # --- диспетчерский конец задания ---
    echo 'ЕКОНЕЦ'
} > "$HERE/../тест-задание.b6"
echo "колода: $HERE/../тест-задание.b6 ($(wc -l < "$MRK") карт разметки)"
