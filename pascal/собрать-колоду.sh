#!/bin/bash
# Сборка колоды задания: <исходник.pas> <файл-данных> [выход.b6]
# Колода транслирует программу компилятором Паскаль-Монитор 15.1
# (восстановленным проектом pascal-re) из PERSO тома 2348 и выполняет её.
#
# Текст данных и исходника готовится к набору на перфокартах ГОСТ-10859:
# в наборе нет строчных букв и буквы Ё (традиционно её заменяют Е),
# поэтому перед перфорацией текст переводится в верхний регистр,
# а Ё -> Е.  Без этого слово «ЗВЁЗДОЧКУ» при чтении распадается на
# «ЗВ ДОЧКУ» (Ё читается пробелом) и схемы ДРАКОН переносятся неверно.
set -e
PAS="$1"; DATA="${2:-}"; OUT="${3:-job.b6}"
gost() {
    # ГОСТ-10859: верхний регистр, Ё->Е, типографские знаки -> доступные
    sed 's/[ёЁ]/Е/g; s/[«»]/"/g; s/—/-/g; s/–/-/g; s/…/.../g' "$1" \
        | tr '[:lower:]' '[:upper:]'
}
{
    echo "user 419999 зс5^"
    echo "лен 40(2348)^"
    echo "eeв1а3"
    echo "*name"
    echo "*no lo"
    echo "*call yesmemory"
    echo "*perso:402570"
    echo "*stand"
    echo "*call *pascal"
    gost "$PAS"
    echo "*execute"
    [ -n "$DATA" ] && gost "$DATA"
    echo "*end file"
    echo '``````'
    echo 'ЕКОНЕЦ'
} > "$OUT"
echo "колода: $OUT"
